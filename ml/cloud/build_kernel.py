#!/usr/bin/env python3
"""Build a single Kaggle Python-script kernel containing existing Smart Sort ML code.

Avoids a private GitHub clone or secrets inside Kaggle. Kaggle kernels push only
needs smart_sort_kaggle.py and kernel-metadata.json, with no Python source copied
by hand. The original ml/*.py files are never changed.
"""
import argparse
import json
from pathlib import Path


def build(args):
    repo = Path(args.repo_root).resolve()
    cloud = Path(__file__).resolve().parent
    out = Path(args.output).resolve()
    owner = args.owner.strip().lower()
    dataset_slug = args.dataset_slug.strip().lower()
    kernel_slug = args.kernel_slug.strip().lower()
    if not all(x and x.replace("-", "").replace("_", "").isalnum()
               for x in (owner, dataset_slug, kernel_slug)):
        raise SystemExit("Owner and slugs must use letters, digits, hyphens, or underscores.")
    if args.epochs < 1 or args.batch_size < 1:
        raise SystemExit("epochs and batch size must be positive")
    sources = {}
    for name in ("setup_data.py", "train_data.py"):
        p = repo / "ml" / name
        if not p.is_file():
            raise SystemExit(f"Missing existing Smart Sort script: {p}")
        sources[name] = p.read_text(encoding="utf-8")
    config = {
        "mode": args.mode,
        "epochs": args.epochs,
        "batch_size": args.batch_size,
        "source_commit": args.source_commit,
        "dataset_ref": f"{owner}/{dataset_slug}",
        "dataset_slug": dataset_slug,
    }
    out.mkdir(parents=True, exist_ok=True)
    payload = ("# Generated by Smart Sort build_kernel.py; do not manually edit\n"
               f"KAGGLE_CONFIG = {config!r}\n"
               f"EMBEDDED_SOURCES = {sources!r}\n\n"
               + (cloud / "kaggle_runner.py").read_text(encoding="utf-8"))
    (out / "smart_sort_kaggle.py").write_text(payload, encoding="utf-8")
    metadata = {
        "id": f"{owner}/{kernel_slug}",
        "title": kernel_slug.replace("-", " ").title(),
        "code_file": "smart_sort_kaggle.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": True,
        "enable_internet": True,  # Required for ImageNet MobileNetV2 weights on first use.
        "machine_shape": "NvidiaTeslaT4",
        "dataset_sources": [f"{owner}/{dataset_slug}"],
        "competition_sources": [],
        "kernel_sources": [],
        "model_sources": [],
    }
    (out / "kernel-metadata.json").write_text(json.dumps(metadata, indent=2), encoding="utf-8")
    print(f"Built Kaggle script at {out}; dataset: {owner}/{dataset_slug}; mode={args.mode}")
    print("No model training or Kaggle API calls were performed by this build command.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo-root", default=".")
    parser.add_argument("--output", required=True)
    parser.add_argument("--owner", required=True)
    parser.add_argument("--dataset-slug", required=True)
    parser.add_argument("--kernel-slug", default="smartsort-gpu-trainer")
    parser.add_argument("--mode", choices=("prepared", "raw"), default="prepared")
    parser.add_argument("--epochs", type=int, default=25)
    parser.add_argument("--batch-size", type=int, default=32)
    parser.add_argument("--source-commit", default="local")
    build(parser.parse_args())
